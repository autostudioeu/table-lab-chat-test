#!/usr/bin/env python3
"""Trivial concatenation: inline the <link>/<script src> files of index.html and admin.html
into ../dist/ordering.html and ../dist/admin.html. No bundler, no minification, no transforms."""
import re, pathlib
SRC = pathlib.Path(__file__).parent
DIST = SRC.parent / "dist"; DIST.mkdir(exist_ok=True)

def read(p): return (SRC / p).read_text(encoding="utf-8")
def safe(js): return js.replace("</script", "<\\/script")

def inline(html, skip=(), extra_head=""):
    html = re.sub(r'<link rel="stylesheet" href="([^"]+)">', lambda m: "<style>\n" + read(m.group(1)) + "\n</style>", html)
    def scr(m):
        src = m.group(1)
        if src in skip: return "<!-- omitted from single-file build: " + src + " -->"
        return "<script>/* ---- " + src + " ---- */\n" + safe(read(src)) + "\n</script>"
    html = re.sub(r'<script src="([^"]+)"></script>', scr, html)
    return html.replace("</head>", extra_head + "</head>", 1)

# 1) customer + kitchen + checkout/split, hash routes only (#table=7, #kitchen)
o = inline(read("index.html"))
o = o.replace("<title>", "<!-- Single-file build of prototype/ (generated by build-dist.py). Open directly; routes: #table=7, #menu, #cart, #pay, #kitchen -->\n<title>", 1)
(DIST / "ordering.html").write_text(o, encoding="utf-8")

# 2) admin with pdf.js + worker inlined (worker via blob URL). Tesseract OCR omitted (too heavy for one file).
worker = safe(read("vendor/pdfjs/pdf.worker.min.js"))
head = ('<script id="pdfjs-worker-src" type="text/plain">' + worker + '</script>\n'
        '<script>window.PDF_WORKER_SRC = URL.createObjectURL(new Blob([document.getElementById("pdfjs-worker-src").textContent], {type: "text/javascript"}));'
        'window.CUSTOMER_URL = "ordering.html"; window.OCR_DISABLED = true;</script>\n')
a = inline(read("admin.html"), skip=("vendor/tesseract/tesseract.min.js",), extra_head=head)
(DIST / "admin.html").write_text(a, encoding="utf-8")
(DIST / "sample-menu.csv").write_text(read("sample-menu.csv"), encoding="utf-8")
for f in sorted(DIST.iterdir()): print(f, f.stat().st_size)
